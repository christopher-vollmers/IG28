def parse_td2_bed(bed_path,cds_coords):
    with open(bed_path) as f:
        f.readline()
        for line in f:
            if 'type:complete;' not in line:
                continue
            parts = line.strip().split("\t")
            tid = parts[0]
            info=parts[3].split(':')[-1].split('(')[0].split('-')
            direction = parts[5]
            if direction == '+':
                start, end = int(info[0]), int(info[1])
            elif direction == '-':
                start, end = int(info[1]), int(info[0])
            cds_coords[tid] = (start, end)
    return cds_coords


def run_td2(reference_corrected_isoforms,temp_path):
    read_count = 0
    TD2_dict={}
    reads_per_file=50000
    orig_dir = os.getcwd()

    abs_path=os.path.abspath(temp_path)

    os.chdir(temp_path)
    os.system(f'rm -r temp_{reference_corrected_isoforms.split(".fasta")[0]}*')
    out = open(f'temp_{reference_corrected_isoforms}', 'w')
    for name, seq, qual in mp.fastx_read(reference_corrected_isoforms):
        if read_count >= reads_per_file:
            out.close()
            os.system(f'TD2.LongOrfs --strand-specific --complete-orfs-only -t temp_{reference_corrected_isoforms} 2>/dev/null')
            os.system(f'TD2.Predict -t temp_{reference_corrected_isoforms} 2>/dev/null')
            TD2_dict=parse_td2_bed(f'{abs_path}/temp_{reference_corrected_isoforms}.TD2.bed',TD2_dict)
            read_count = 0
            os.system(f'rm -r temp_{reference_corrected_isoforms.split(".fasta")[0]}*')
            out = open(f'temp_{reference_corrected_isoforms}', 'w')
        out.write(f">{name}\n{seq}\n")
        read_count += 1

    out.close()
    os.system(f'TD2.LongOrfs --strand-specific --complete-orfs-only -t temp_{reference_corrected_isoforms} 2>/dev/null')
    os.system(f'TD2.Predict -t temp_{reference_corrected_isoforms} 2>/dev/null')
    TD2_dict=parse_td2_bed(f'{abs_path}/temp_{reference_corrected_isoforms}.TD2.bed',TD2_dict)
    #    os.system(f'rm -r temp_{reference_corrected_isoforms.split(".fasta")[0]}*')
    os.chdir(orig_dir)
    return TD2_dict


